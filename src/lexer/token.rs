#[derive(Debug, Clone, PartialEq)]
pub enum Token {
    Identifier(String),
    Number(f64),
    StringLiteral(String),
    /// Raw content between backticks, still with `${...}` and escape characters. The parser interprets it.
    TemplateString(String),
    Boolean(bool),
    Null,
    Var,
    Const,
    Type,
    If,
    Else,
    For,
    In,
    While,
    Func,
    Return,
    Async,
    Await,
    Match,
    Switch,
    Case,
    Default,
    Break,
    Continue,
    Fallthrough,
    And,
    Or,
    Not,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Equal,
    EqualEqual,
    PlusEqual,
    MinusEqual,
    StarEqual,
    SlashEqual,
    Bang,
    BangEqual,
    Greater,
    GreaterEqual,
    Less,
    LessEqual,
    Arrow,
    FatArrow,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Dot,
    Semicolon,
    Colon,
    /// A character that does not belong to the language.
    Illegal(char),
    EOF,
}